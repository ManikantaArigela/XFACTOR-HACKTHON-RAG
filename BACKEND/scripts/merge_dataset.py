def merge():
    backend_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    raw_path = os.path.join(backend_dir, "data", "raw", "instagram_posts.json")
    
    with open(raw_path, "r", encoding="utf-8") as f:
        existing = json.load(f)

    existing_ids = {p.get("instagram_post_id") for p in existing}

    formatted_new = []
    for item in new_products:
        post_id = f"post_{item['id'].lower()}"
        if post_id in existing_ids:
            continue

        p_name = item["product_name"]
        brand = item["brand"]
        cat = item["category"]
        mrp = item["mrp"]
        sp = item["selling_price"]
        disc = item["discount_percent"]
        feats = ", ".join(item["features"])

        ram = None
        storage = None
        for f in item["features"]:
            if "RAM" in f:
                ram = f.strip()
            if "storage" in f or "SSD" in f:
                storage = f.strip()

        caption = f"🔥 Offer Alert at Arudhra Mobile Stores, Pithapuram! {p_name} ({cat}) by {brand}. Key Features: {feats}. MRP: ₹{mrp:,.2f}, Special Arudhra Price: ₹{sp:,.2f} ({disc}% off)! Available at Arudhra Mobile Stores, Pithapuram. Home delivery available across Kakinada District. Call 91777 75 777! #{brand} #{cat.replace(' ', '')} #ArudhraMobiles #Pithapuram"

        formatted_new.append({
            "instagram_post_id": post_id,
            "product_name": p_name,
            "brand": brand,
            "category": cat.lower(),
            "caption": caption,
            "post_url": item.get("source_url", "https://www.arudhra.com/products/"),
            "poster_image_url": item.get("image"),
            "product_image_url": item.get("image"),
            "image": item.get("image"),
            "selling_price": sp,
            "mrp": mrp,
            "ram": ram,
            "storage": storage,
            "features": item["features"],
            "posted_at": "2026-09-18T12:00:00Z"
        })

    combined = existing + formatted_new
    with open(raw_path, "w", encoding="utf-8") as f:
        json.dump(combined, f, indent=2, ensure_ascii=False)

    print(f"[MERGE SUCCESS] Appended {len(formatted_new)} new products! Total catalog dataset count: {len(combined)}")

if __name__ == "__main__":
    merge()
